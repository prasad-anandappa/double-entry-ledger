-- Double-entry ledger schema (portable across PostgreSQL and H2/PostgreSQL mode).
-- All monetary values are stored as BIGINT minor units (e.g. cents). No floats, ever.

CREATE TABLE accounts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(32)  NOT NULL UNIQUE,
    name       VARCHAR(200) NOT NULL,
    type       VARCHAR(16)  NOT NULL,
    currency   VARCHAR(3)   NOT NULL,
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMP    NOT NULL,
    CONSTRAINT ck_accounts_type CHECK (type IN ('ASSET','LIABILITY','EQUITY','REVENUE','EXPENSE'))
);

CREATE TABLE journal_entries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    value_date      DATE         NOT NULL,
    description     VARCHAR(500) NOT NULL,
    reference       VARCHAR(100),
    idempotency_key VARCHAR(200) UNIQUE,
    payload_hash    VARCHAR(64),
    created_at      TIMESTAMP    NOT NULL
);

CREATE TABLE journal_lines (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id    BIGINT NOT NULL REFERENCES journal_entries (id),
    account_id  BIGINT NOT NULL REFERENCES accounts (id),
    debit_minor BIGINT NOT NULL,
    credit_minor BIGINT NOT NULL,
    CONSTRAINT ck_lines_non_negative CHECK (debit_minor >= 0 AND credit_minor >= 0),
    -- exactly one side of a line may carry an amount: a line is a debit XOR a credit
    CONSTRAINT ck_lines_one_side CHECK ((debit_minor > 0 AND credit_minor = 0)
                                     OR (debit_minor = 0 AND credit_minor > 0))
);

CREATE INDEX idx_lines_account ON journal_lines (account_id);
CREATE INDEX idx_lines_entry ON journal_lines (entry_id);

CREATE TABLE reconciliation_runs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at         TIMESTAMP NOT NULL,
    statement_lines    INTEGER   NOT NULL,
    ledger_effects     INTEGER   NOT NULL,
    matched            INTEGER   NOT NULL,
    exception_count    INTEGER   NOT NULL
);

CREATE TABLE reconciliation_exceptions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id       BIGINT       NOT NULL REFERENCES reconciliation_runs (id),
    type         VARCHAR(32)  NOT NULL,
    account_code VARCHAR(32)  NOT NULL,
    value_date   DATE         NOT NULL,
    amount_minor BIGINT       NOT NULL,
    reference    VARCHAR(100),
    description  VARCHAR(500),
    CONSTRAINT ck_exc_type CHECK (type IN ('MISSING_IN_LEDGER','MISSING_ON_STATEMENT','AMOUNT_MISMATCH'))
);
